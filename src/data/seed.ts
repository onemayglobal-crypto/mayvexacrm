export function taskFromLead(lead: { id: string; name: string; nextAction: string }) {
  if (!lead.nextAction.trim()) return null
  return {
    id: uid('task'),
    leadId: lead.id,
    kind: 'followup' as const,
    title: `${lead.nextAction} — ${lead.name}`,
    detail: 'Created from a new lead.',
    actionLabel: 'Done',
    doneLabel: 'Undo',
    done: false,
    dueDate: isoDays(1),
  }
}
